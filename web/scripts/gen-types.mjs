// Generate src/lib/contracts.ts from ../contracts/schemas.json (contracts v1.1).
//
// The backend serialises every field of a pydantic model (defaults included), so on the wire a
// field with a default is always present. JSON Schema marks those fields optional; we mark them
// required here so response types are exact. Request bodies get optional fields via helper types
// in src/lib/api-types.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../contracts/schemas.json");
const out = resolve(here, "../src/lib/contracts.ts");

const schema = JSON.parse(readFileSync(src, "utf-8"));
const defs = schema.$defs ?? {};

for (const def of Object.values(defs)) {
  if (def && def.type === "object" && def.properties) {
    def.required = Object.keys(def.properties);
  }
}

// A root object that references every definition, so each one is emitted as a named export.
const root = {
  title: "ContractsRoot",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(Object.keys(defs).map((k) => [k, { $ref: `#/$defs/${k}` }])),
  $defs: defs,
};

const ts = await compile(root, "ContractsRoot", {
  bannerComment:
    "/* eslint-disable */\n/**\n * GENERATED by scripts/gen-types.mjs from contracts/schemas.json (contracts v1.1).\n * Do not edit by hand: run `npm run gen:types`.\n * Money and rates are STRING decimals on the wire.\n */",
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: false,
  format: true,
});

writeFileSync(out, ts, "utf-8");
console.log(`wrote ${out} (${Object.keys(defs).length} definitions)`);
